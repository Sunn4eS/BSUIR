# ---------------------------------------------------------------- helpers ----
def boundary_point(cx, cy, hx, hy, kind, px, py):
    """Точка на границе узла (с центром (cx,cy), полуосями hx,hy) в сторону (px,py)."""
    dx, dy = px - cx, py - cy
    if dx == 0 and dy == 0:
        return cx, cy
    if kind == "rule":
        r = hx
        t = r / math.hypot(dx, dy)
    elif kind in ("org",):
        t = 1.0 / math.hypot(dx / hx, dy / hy)
    else:
        tx = hx / abs(dx) if dx else float("inf")
        ty = hy / abs(dy) if dy else float("inf")
        t = min(tx, ty)
    return cx + dx * t, cy + dy * t


def draw_node(ax, nd):
    x, y, w, h = nd["x"], nd["y"], nd["w"], nd["h"]
    kind = nd["kind"]
    col = COL[kind]
    if kind == "event":
        hw, hh = w / 2, h / 2
        pts = [(x, y + hh), (x + hw, y + hh / 3), (x + hw, y - hh / 3),
               (x, y - hh), (x - hw, y - hh / 3), (x - hw, y + hh / 3)]
        p = Polygon(pts, closed=True, facecolor=col["fill"], edgecolor="black",
                    lw=col["lw"], zorder=3)
        ax.add_patch(p)
    elif kind == "func":
        p = FancyBboxPatch((x - w / 2, y - h / 2), w, h,
                           boxstyle="round,pad=0.02,rounding_size=0.10",
                           facecolor=col["fill"], edgecolor="black",
                           lw=col["lw"], zorder=3)
        ax.add_patch(p)
    elif kind == "obj":
        p = Rectangle((x - w / 2, y - h / 2), w, h, facecolor=col["fill"],
                      edgecolor="black", lw=col["lw"], zorder=3)
        ax.add_patch(p)
    elif kind == "org":
        p = Ellipse((x, y), w, h, facecolor=col["fill"], edgecolor="black",
                    lw=col["lw"], zorder=3)
        ax.add_patch(p)
    elif kind == "rule":
        r = w / 2
        p = Circle((x, y), r, facecolor=col["fill"], edgecolor="black",
                   lw=col["lw"], zorder=3)
        ax.add_patch(p)
    fs = FS[kind]
    if kind == "func":
        ax.text(x, y, nd["text"], ha="center", va="center", fontsize=fs,
                weight="bold", zorder=4)
    elif kind == "rule":
        ax.text(x, y, nd["text"], ha="center", va="center", fontsize=fs,
                weight="bold", zorder=4)
    else:
        ax.text(x, y, nd["text"], ha="center", va="center", fontsize=fs,
                zorder=4)


def draw_edges(ax, nodes, edges):
    nb = {n["id"]: n for n in nodes}

    for e in edges:
        a, b = nb[e["a"]], nb[e["b"]]
        wps = e.get("wps", [])
        dash = e.get("kind") == "dash"
        # выход из узла a (к первому waypoint или к узлу b)
        first_wp = wps[0] if wps else (b["x"], b["y"])
        pa = boundary_point(a["x"], a["y"], a["w"] / 2, a["h"] / 2, a["kind"],
                            first_wp[0], first_wp[1])
        poly = [pa] + list(wps)
        # вход в узел b (от последнего waypoint или от узла a)
        last_wp = wps[-1] if wps else (a["x"], a["y"])
        pb = boundary_point(b["x"], b["y"], b["w"] / 2, b["h"] / 2, b["kind"],
                            last_wp[0], last_wp[1])
        poly.append(pb)
        if dash:
            ax.plot(*zip(*poly), color="black", lw=1.3, ls=(0, (4, 3)), zorder=2)
            continue
        # сегменты ломаной
        for i in range(len(poly) - 1):
            ax.plot([poly[i][0], poly[i + 1][0]],
                    [poly[i][1], poly[i + 1][1]], color="black", lw=1.5, zorder=2)
        # наконечник на последнем сегменте
        ax.add_patch(FancyArrowPatch(posA=poly[-2], posB=poly[-1],
                                     arrowstyle="-|>", mutation_scale=15,
                                     lw=0, color="black", zorder=3))


def render(nodes, edges, fname, title):
    # проверка пересечений
    warn = 0
    for i in range(len(nodes)):
        for j in range(i + 1, len(nodes)):
            a, b = nodes[i], nodes[j]
            if (abs(a["x"] - b["x"]) < (a["w"] + b["w"]) / 2 * 0.99 and
                    abs(a["y"] - b["y"]) < (a["h"] + b["h"]) / 2 * 0.99):
                print(f"  ! overlap: {a['id']} ({a['text'][:20]}) x {b['id']}")
                warn += 1
    xs = [n["x"] for n in nodes] + [p[0] for e in edges for p in e.get("wps", [])]
    ys = [n["y"] for n in nodes] + [p[1] for e in edges for p in e.get("wps", [])]
    for e in edges:
        for p in e.get("wps", []):
            xs.append(p[0]); ys.append(p[1])
    pad = 1.3
    fig, ax = plt.subplots(figsize=(11, 9.5))
    ax.set_xlim(min(xs) - pad, max(xs) + pad)
    ax.set_ylim(min(ys) - pad, max(ys) + pad)
    ax.set_aspect("equal")
    ax.axis("off")
    ax.set_title(title, fontsize=15, pad=14)
    draw_edges(ax, nodes, edges)
    for n in nodes:
        draw_node(ax, n)
    fig.tight_layout()
    fig.savefig(fname, dpi=200, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print(f"  диаграмма {os.path.basename(fname)} сохранена (пересечений: {warn})")


def N(kind, text, x, y, w=None, h=None, iid=None, fx=None, bold=False):
    std = {"event": (1.85, 0.62), "func": (2.6, 0.7), "obj": (2.0, 0.55),
           "org": (1.7, 0.55), "rule": (0.7, 0.7)}
    if w is None:
        w, h = std[kind]
    if h is None:
        h = std[kind][1]
    d = {"id": iid or f"{kind}_{x}_{y}", "kind": kind, "text": text,
         "x": x, "y": y, "w": w, "h": h}
    if fx:
        d["fx"] = fx
    return d


